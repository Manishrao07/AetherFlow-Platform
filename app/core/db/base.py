"""SQLAlchemy declarative base, naming conventions and reusable column helpers.

What: the single ``Base`` all models inherit from, plus mixins for UUID primary keys and
created/updated timestamps, and a helper that turns a Python Enum into a CHECK-constrained
string column.
Why: a constraint naming convention makes Alembic migrations deterministic and lets us
drop/alter constraints by name. Non-native enums (VARCHAR + CHECK) avoid the painful
"ALTER TYPE" migrations that native Postgres enums need when a state is added.
Connects to: every model in ``app/models`` and ``migrations/env.py``.
"""

from __future__ import annotations

import enum
import uuid
from datetime import datetime
from typing import TypeVar

import sqlalchemy as sa
from sqlalchemy import MetaData
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# WHY: explicit names for every constraint/index type; Alembic autogenerate relies on it.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

E = TypeVar("E", bound=enum.Enum)


class Base(DeclarativeBase):
    """Declarative base for all ORM models."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class UUIDPrimaryKeyMixin:
    """UUID primary key generated by Postgres.

    WHY UUIDs: IDs are safe to expose in URLs (no enumeration of "run 1, run 2, ...") and
    can be generated without a central sequence, which helps if we later shard or merge.
    """

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        server_default=sa.text("gen_random_uuid()"),
    )


class TimestampMixin:
    """created_at / updated_at maintained by the database clock (single source of time)."""

    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), server_default=sa.func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True),
        server_default=sa.func.now(),
        onupdate=sa.func.now(),
        nullable=False,
    )


def enum_column(enum_cls: type[E], name: str) -> sa.Enum:
    """Build a VARCHAR + CHECK column type from a Python Enum (stores the enum *value*)."""
    return sa.Enum(
        enum_cls,
        name=name,
        native_enum=False,
        create_constraint=True,
        length=32,
        values_callable=lambda members: [m.value for m in members],
        validate_strings=True,
    )
